THEME_NAME = "MahoFiles"
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")

FALLBACK = {
    "background": "#121112",
    "surface": "#1d1a1b",
    "surface_elevated": "#292526",
    "foreground": "#f0e9e8",
    "foreground_muted": "#bdb4b3",
    "accent": "#d3aaa8",
    "accent_soft": "#4a3637",
    "border": "#8e8484",
    "focus": "#d3aaa8",
    "shadow": "#000000",
    "critical": "#ffb4ab",
}


def _valid_color(value: object, fallback: str) -> str:
    text = str(value or "").strip()
    return text.lower() if HEX.fullmatch(text) else fallback


def palette_path() -> Path:
    cache = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache"))
    return cache / "maho/theme/active.json"


def theme_root() -> Path:
    data = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share"))
    return data / "themes" / THEME_NAME


def load_palette(path: Path) -> dict[str, str]:
    data: dict[str, object] = {}
    if path.is_file():
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            loaded = {}
        if isinstance(loaded, dict):
            data = loaded

    semantic = data.get("semantic") if isinstance(data.get("semantic"), dict) else {}
    colors = data.get("colors") if isinstance(data.get("colors"), dict) else {}

    def role(name: str, legacy: str | None = None) -> str:
        candidate = semantic.get(name) if isinstance(semantic, dict) else None
        if candidate is None and legacy and isinstance(colors, dict):
            candidate = colors.get(legacy)
        return _valid_color(candidate, FALLBACK[name])

    return {
        "background": role("background", "background"),
        "surface": role("surface", "surface_container"),
        "surface_elevated": role("surface_elevated", "surface_container_high"),
        "foreground": role("foreground", "foreground"),
        "foreground_muted": role("foreground_muted", "muted"),
        "accent": role("accent", "primary"),
        "accent_soft": role("accent_soft", "surface_container_high"),
        "border": role("border", "outline"),
        "focus": role("focus", "primary"),
        "shadow": role("shadow"),
        "critical": role("critical", "error"),
    }


