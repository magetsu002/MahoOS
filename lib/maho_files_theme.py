def write_theme(output: Path, palette_file: Path) -> tuple[Path, Path]:
    gtk_dir = output / "gtk-3.0"
    gtk_dir.mkdir(parents=True, exist_ok=True)
    css_path = gtk_dir / "gtk.css"
    index_path = output / "index.theme"

    palette = load_palette(palette_file)
    css_path.write_text(render_css(palette), encoding="utf-8")
    index_path.write_text(
        "[Desktop Entry]\n"
        "Type=X-GNOME-Metatheme\n"
        "Name=Maho Files\n"
        "Comment=Private GTK3 material for Maho Files\n",
        encoding="utf-8",
    )
    return css_path, index_path


def doctor(palette_file: Path, output: Path) -> int:
    palette = load_palette(palette_file)
    css = render_css(palette)
    checks = {
        "palette": all(HEX.fullmatch(value) for value in palette.values()),
        "isolated_theme": output.name == THEME_NAME,
        "translucent_window": "alpha(@maho_bg, 0.62)" in css,
        "premium_close": "button.titlebutton.close:hover" in css,
        "native_views": "treeview.view" in css and "iconview.view" in css,
    }
    failed = False
    for name, ok in checks.items():
        print(f"{'PASS' if ok else 'FAIL'}  {name}")
        failed = failed or not ok
    return 1 if failed else 0


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(description=__doc__)
    sub = root.add_subparsers(dest="command")

    render = sub.add_parser("render")
    render.add_argument("--palette", type=Path, default=palette_path())
    render.add_argument("--output", type=Path, default=theme_root())

    check = sub.add_parser("doctor")
    check.add_argument("--palette", type=Path, default=palette_path())
    check.add_argument("--output", type=Path, default=theme_root())

    return root


def main(argv: list[str]) -> int:
    args = parser().parse_args(argv)
    command = args.command or "render"
    if command == "render":
        css, index = write_theme(args.output, args.palette)
        print(css)
        print(index)
        return 0
    if command == "doctor":
        return doctor(args.palette, args.output)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
