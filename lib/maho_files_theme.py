"""Render the isolated GTK3 material used by Maho Files.

Maho Files keeps Thunar as the file-management engine. This module only turns
Maho's active palette into a named GTK theme that can be applied to the Thunar
process with GTK_THEME=MahoFiles. It never edits the user's global GTK theme.
"""

